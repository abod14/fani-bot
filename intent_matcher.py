def match_professions(text: str, limit: int = 3) -> list[str]:
    """يرجّع قائمة profession_id الأقرب لوصف العميل، مرتّبة حسب عدد الكلمات
    المفتاحية المطابقة (الأكثر تطابقًا أولًا). قائمة فارغة يعني ما قدرنا نتعرّف
    على المشكلة تلقائيًا."""
    text_norm = (text or "").strip()
    if not text_norm:
        return []

    scores: dict[str, int] = {}
    for profession_id, keywords in KEYWORDS.items():
        for kw in keywords:
            if kw in text_norm:
                scores[profession_id] = scores.get(profession_id, 0) + 1

    ranked = sorted(scores.items(), key=lambda item: -item[1])
    return [profession_id for profession_id, _ in ranked[:limit]]
