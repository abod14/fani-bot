def _eg_words():
    global _eg_vocab
    if _eg_vocab is None:
        v = set(_EG_SUFFIX)
        names = [x["name"] for x in _src("oad_eg_shiyakha.json")] + [x["name"] for x in _src("oad_eg.json")]
        names += [a["name_ar"] for a in _src("eg_areas.json")["areas"]]
