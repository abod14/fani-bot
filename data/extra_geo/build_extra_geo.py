# نطاقات المعرّفات بعيدة تمامًا عن معرّفات السعودية (مناطق 1-13، مدن ≤ 23642،
# أحياء ~10^10) حتى ما يصير أي تعارض بنفس الجداول.
REGION_BASE = 100_000
CITY_BASE = 10_000_000
DISTRICT_BASE = 900_000_000_000


def _hid(*parts) -> int:
    return zlib.crc32("|".join(parts).encode("utf-8"))


def build() -> dict:
    regions, cities, districts = [], [], []
    seen = set()

    def add_id(kind, value):
        key = (kind, value)
        assert key not in seen, f"تعارض معرّف {kind}: {value}"
        seen.add(key)
        return value

    for cc, region_list in merge_sources().items():
        for region_name, city_list in region_list:
            rid = add_id("r", REGION_BASE + _hid(cc, region_name) % 900_000)
            regions.append({"id": rid, "country": cc, "name": region_name})
            for city_name, lat, lon, dist_list in city_list:
                cid = add_id("c", CITY_BASE + _hid(cc, region_name, city_name) % 89_999_999)
                cities.append({
                    "id": cid, "region_id": rid, "country": cc, "name": city_name,
                    "lat": lat, "lon": lon,
                })
                names = set()
                for d_name, d_lat, d_lon in dist_list:
                    assert d_name not in names, f"حي مكرر: {city_name} / {d_name}"
                    names.add(d_name)
                    did = add_id("d", DISTRICT_BASE + _hid(cc, city_name, d_name))
                    districts.append({
                        "id": did, "city_id": cid, "name": d_name, "lat": d_lat, "lon": d_lon,
                    })
    return {"regions": regions, "cities": cities, "districts": districts}


